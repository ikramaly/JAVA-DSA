package JavaRivision;

public class StringRivision {
    public static void main(String[] args) {
        String s1 = "Ikram";
        s1 = s1.concat("Ali");
        System.out.println(s1);
        int a = 100;
        byte b = (byte) a;
        System.out.println(a);
        System.out.println(b);
        double d = 1920.39;
        int d1 = (int) d;
        System.out.println(d);
        System.out.println(d1);
    }
}
